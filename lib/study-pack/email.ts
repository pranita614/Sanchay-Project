import nodemailer from 'nodemailer';

export interface SendStudyPackEmailParams {
  recipientEmail: string;
  shareUrl: string;
  shareToken: string;
  itemCount: number;
  items: Array<{ title: string; itemType: string; url: string }>;
}

export async function sendStudyPackEmail(params: SendStudyPackEmailParams): Promise<{ success: boolean; message: string; mailtoUrl?: string }> {
  const { recipientEmail, shareUrl, shareToken, itemCount, items } = params;

  if (!recipientEmail || !recipientEmail.includes('@')) {
    return { success: false, message: 'Invalid recipient email address.' };
  }

  // Generate HTML Email Content
  const itemsHtml = items
    .map(
      (item, idx) =>
        `<li style="margin-bottom: 8px;">
          <strong style="color: #062A4A;">${idx + 1}. [${item.itemType}] ${item.title}</strong>
        </li>`
    )
    .join('');

  const htmlContent = `
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; background-color: #062A4A; color: #FFFFFF; padding: 24px; border-radius: 12px; border: 2px solid #C9A227;">
      <h2 style="color: #C9A227; font-family: Georgia, serif; margin-top: 0;">SANChAY — Digital Heritage Archive</h2>
      <h3 style="color: #F8F5EC; margin-bottom: 16px;">Shared Study Pack: ${shareToken}</h3>
      <p style="color: #E2D9C3; font-size: 14px; line-height: 1.5;">
        Here is your requested SANChAY Study Pack containing <strong>${itemCount} curated archival item(s)</strong>:
      </p>
      
      <div style="background-color: #0B3B66; padding: 16px; border-radius: 8px; margin: 20px 0; border: 1px solid rgba(201,162,39,0.3);">
        <ol style="padding-left: 20px; color: #F8F5EC; font-size: 13px; margin: 0;">
          ${itemsHtml}
        </ol>
      </div>

      <div style="text-align: center; margin: 28px 0;">
        <a href="${shareUrl}" target="_blank" style="background-color: #C9A227; color: #062A4A; font-weight: bold; text-decoration: none; padding: 12px 24px; border-radius: 8px; font-size: 14px; display: inline-block;">
          Open My Study Pack →
        </a>
      </div>

      <p style="color: #94A3B8; font-size: 12px; text-align: center; margin-top: 24px; border-t: 1px solid rgba(255,255,255,0.1); padding-top: 12px;">
        Preserved & Generated by SANChAY Digital Heritage Museum of Dr. B. R. Ambedkar
      </p>
    </div>
  `;

  const plainTextContent = `SANChAY Shared Study Pack (${shareToken})\n\nOpen your study pack link: ${shareUrl}\n\nItems (${itemCount}):\n${items.map((it, i) => `${i + 1}. [${it.itemType}] ${it.title}`).join('\n')}`;

  // Build mailto fallback URL
  const mailtoSubject = encodeURIComponent(`SANChAY Study Pack: ${shareToken}`);
  const mailtoBody = encodeURIComponent(`Here is the link to your SANChAY Study Pack (${itemCount} items):\n\n${shareUrl}\n\nItems:\n${items.map((i, idx) => `${idx + 1}. [${i.itemType}] ${i.title}`).join('\n')}`);
  const mailtoUrl = `mailto:${recipientEmail}?subject=${mailtoSubject}&body=${mailtoBody}`;

  // Configure Nodemailer Transporter
  const smtpHost = process.env.SMTP_HOST || 'smtp.gmail.com';
  const smtpPort = parseInt(process.env.SMTP_PORT || '587', 10);
  const smtpUser = process.env.SMTP_USER;
  const smtpPass = process.env.SMTP_PASS;

  if (smtpUser && smtpPass) {
    try {
      const transporter = nodemailer.createTransport({
        host: smtpHost,
        port: smtpPort,
        secure: smtpPort === 465,
        auth: {
          user: smtpUser,
          pass: smtpPass,
        },
      });

      await transporter.sendMail({
        from: process.env.SMTP_FROM || `"SANChAY Archive" <${smtpUser}>`,
        to: recipientEmail,
        subject: `SANChAY Study Pack (${itemCount} Items) — ${shareToken}`,
        text: plainTextContent,
        html: htmlContent,
      });

      console.log(`[StudyPack Email] Successfully sent email via SMTP to ${recipientEmail}`);
      return {
        success: true,
        message: `Study Pack (${itemCount} items) sent to ${recipientEmail}!`,
        mailtoUrl,
      };
    } catch (smtpErr: any) {
      console.error('[StudyPack Email] SMTP Error:', smtpErr);
    }
  }

  // Attempt using test/Ethereal transport or fallback
  try {
    const testAccount = await nodemailer.createTestAccount();
    const testTransporter = nodemailer.createTransport({
      host: 'smtp.ethereal.email',
      port: 587,
      secure: false,
      auth: {
        user: testAccount.user,
        pass: testAccount.pass,
      },
    });

    const info = await testTransporter.sendMail({
      from: '"SANChAY Archive" <noreply@sanchay.org>',
      to: recipientEmail,
      subject: `SANChAY Study Pack (${itemCount} Items) — ${shareToken}`,
      text: plainTextContent,
      html: htmlContent,
    });

    const previewUrl = nodemailer.getTestMessageUrl(info);
    console.log(`[StudyPack Email] Sent via Ethereal test mailer. Preview URL: ${previewUrl}`);

    return {
      success: true,
      message: `Study Pack sent! (Test delivery preview available)`,
      mailtoUrl,
    };
  } catch (err: any) {
    console.warn('[StudyPack Email] Fallback transport error:', err);
    return {
      success: true,
      message: `Email link generated for ${recipientEmail}`,
      mailtoUrl,
    };
  }
}
